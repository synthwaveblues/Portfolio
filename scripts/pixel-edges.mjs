// Generates src/styles/pixelEdges.css: the pixel-shading edge of the cherry sections as inline SVG masks, plus the
// keyframes that step through them. The strip is 2560px wide, so it never repeats within one screen width, and a
// fixed seed keeps it identical on every build and reload. global.css shifts it by half its width on the edges
// where a section closes, so those look different from the ones where it opens.
//
// It comes in frames: each one re-rolls a share of the previous frame's pixels, so stepping through them makes
// the fade shimmer instead of jumping to a new pattern. Frame 0 is what shows with reduced motion.
//
//   node scripts/pixel-edges.mjs

import {writeFileSync} from 'node:fs';

const WIDTH = 2560;
const CELL = 4;
const FRAMES = 10;
// share of pixels re-rolled between two frames
const CHURN = 0.12;
// from the outside in: pixel size inside the 4px cell and how full the row is, like the ASCII ramp . - + * # @
const RAMP = [
  [1, 0.05], [1, 0.08], [1, 0.12], [1, 0.16], [2, 0.2], [2, 0.26], [2, 0.33], [2, 0.4],
  [3, 0.48], [3, 0.56], [3, 0.65], [3, 0.74], [4, 0.82], [4, 0.9], [4, 0.96], [4, 1],
];
const HEIGHT = CELL * RAMP.length;
const COLS = WIDTH / CELL;

// small seeded PRNG, so the output only changes when the seed does
function mulberry32(seed) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// grid[row][col] = is that pixel on
function frames(seed) {
  const random = mulberry32(seed);
  let grid = RAMP.map(([, fill]) => Array.from({length: COLS}, () => random() < fill));
  const out = [grid];
  for (let f = 1; f < FRAMES; f++) {
    grid = grid.map((cells, row) => cells.map(on => (random() < CHURN ? random() < RAMP[row][1] : on)));
    out.push(grid);
  }
  return out;
}

// one stroked path per row: each pixel is a horizontal segment as long and as thick as the pixel,
// and neighbouring full-size pixels merge into one segment
function svg(grid) {
  const rows = RAMP.map(([size], row) => {
    // whole-pixel offset so odd sizes stay sharp at 1x
    const offset = Math.floor((CELL - size) / 2);
    const y = row * CELL + offset + size / 2;
    let d = '';
    let pen = 0; // x where the last segment ended
    let run = null; // [start, end] of the segment being built
    const flush = () => {
      if (!run) return;
      d += d ? `m${run[0] - pen} 0h${run[1] - run[0]}` : `M${run[0]} ${y}h${run[1] - run[0]}`;
      pen = run[1];
      run = null;
    };
    grid[row].forEach((on, col) => {
      if (!on) return;
      const x = col * CELL + offset;
      if (run && run[1] === x) run[1] = x + size;
      else {
        flush();
        run = [x, x + size];
      }
    });
    flush();
    return d ? `<path stroke-width="${size}" d="${d}"/>` : '';
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${WIDTH}" height="${HEIGHT}" stroke="black" shape-rendering="crispEdges">${rows.join('')}</svg>`;
}

const strips = frames(0x5eed1).map(svg);
const vars = strips.map((strip, f) => `    --edge-${f}: url('data:image/svg+xml,${strip}');`);
// --edge is unregistered, so it switches frames instantly at each step instead of blending
const steps = strips.map((_, f) => `    ${+((f / (FRAMES - 1)) * 100).toFixed(2)}% { --edge: var(--edge-${f}); }`);

const css = `/* generated by scripts/pixel-edges.mjs, don't edit by hand */
:root {
    --edge-w: ${WIDTH}px;
${vars.join('\n')}
}

@keyframes edge-shimmer {
${steps.join('\n')}
}
`;

writeFileSync(new URL('../src/styles/pixelEdges.css', import.meta.url), css);
console.log(`pixelEdges.css: ${(css.length / 1024).toFixed(1)} KB, ${FRAMES} frames`);
